// Builds supabase/setup.sql (not committed): the one file to paste into Supabase's SQL editor, made
// from schema.sql, storage.sql, the scoring settings and the campus list.  npm run build:sql
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import scoring from '../public/shared/scoring.config.js';

const dir = fileURLToPath(new URL('../supabase/', import.meta.url));
const read = f => fs.readFileSync(dir + f, 'utf8');
const json = v => `$json$${JSON.stringify(v)}$json$::jsonb`;

/** Settings and starting data. adminProviders: sign-in methods that can be admin ("dev" only in local mode). */
export function seedSql({ adminProviders = ['google'] } = {}) {
  const campus = JSON.parse(read('campus-map.json'));
  const campuses = JSON.parse(fs.readFileSync(new URL('../public/data/campuses.json', import.meta.url), 'utf8'));
  const blocked = JSON.parse(read('blocked-names.json')).names;
  return `-- ── settings and starting data (generated by scripts/build-sql.js) ──
insert into public.settings (key, value) values ('scoring', ${json(scoring)})
  on conflict (key) do update set value = excluded.value;
insert into public.settings (key, value) values ('timezone', '"America/Los_Angeles"')
  on conflict (key) do nothing;
insert into public.settings (key, value) values ('admin_providers', ${json(adminProviders)})
  on conflict (key) do update set value = excluded.value;
insert into public.settings (key, value) values ('blocked_names', ${json(blocked)})
  on conflict (key) do update set value = excluded.value;
insert into public.campuses (id, name, short_name, kind, city, lat, lng, size)
  select c->>'id', c->>'name', c->>'short', c->>'kind', c->>'city', (c->>'lat')::float8, (c->>'lng')::float8, (c->>'size')::float8
  from jsonb_array_elements(${json(campuses)}) c
  on conflict (id) do update set name = excluded.name, short_name = excluded.short_name, kind = excluded.kind,
    city = excluded.city, lat = excluded.lat, lng = excluded.lng, size = excluded.size;
insert into public.maps (id, data, campus_id) values ('campus', ${json(campus)}, 'cal-poly-pomona')
  on conflict (id) do nothing;
-- Before campuses existed every map was Cal Poly Pomona's.
update public.maps set campus_id = 'cal-poly-pomona' where campus_id is null;
-- Admins from the line at the top of setup.sql (skipped while it still says your.email@gmail.com).
insert into public.admins (email)
  select lower(trim(e)) from unnest(string_to_array(coalesce(current_setting('campusspot.admin_emails', true), ''), ',')) as e
  where trim(e) ~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$' and lower(trim(e)) <> 'your.email@gmail.com'
  on conflict do nothing;
`;
}

export function setupSql() {
  return `-- ═══════════════════════════════════════════════════════════════════════════════════════════════
-- CampusSpot: complete database setup for Supabase. Generated by scripts/build-sql.js.
-- Paste this whole file into Supabase → SQL Editor → New query, then press Run.
-- Running it again later is safe: it updates functions and settings and keeps your data.
--
-- ▶ BEFORE YOU RUN: on the next line, replace your.email@gmail.com with the Google account
--   email of your admin (the 1–2 people who may host rounds, edit maps and moderate names).
--   For two admins, separate them with a comma: 'one@gmail.com,two@gmail.com'
--   Only change it in the Supabase editor; don't commit real addresses to GitHub.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════
select set_config('campusspot.admin_emails', 'your.email@gmail.com', false);

${read('schema.sql')}
${read('storage.sql')}
${seedSql()}
-- Later, to add or remove an admin, run one of these lines on its own:
--   insert into public.admins (email) values ('someone@gmail.com');
--   delete from public.admins where email = 'someone@gmail.com';
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(dir + 'setup.sql', setupSql());
  console.log('Wrote supabase/setup.sql');
}
